export const EXERCISE_PROFILES: Readonly<Record<string, ExerciseProfile>> =
  Object.fromEntries(
    rows.map(
      ([
        id,
        method,
        strategy,
        view,
        art,
        minimum,
        joints,
        observable,
        limitation,
        sources,
        options,
      ]) => [
        id,
        {
          id,
          method,
          strategy,
          view,
          art,
          minimum,
          direction: "increase" as const,
          joints,
          observable,
          limitation,
          sources: sources.split(" "),
          ...options,
          validation:
            method === "existing"
              ? "existing-logic-tests"
              : method === "confirmation"
                ? "not-observable"
                : "experimental-no-physical-validation",
        },
      ],
    ),
  );
export function exerciseProfile(id: string): ExerciseProfile | undefined {
  return Object.hasOwn(EXERCISE_PROFILES, id)
    ? EXERCISE_PROFILES[id]
    : undefined;
}
export const CAMERA_VIEWS: Record<ExerciseProfile["view"], string> = {
  side: "Side view · camera near hip height",
  "front-or-side": "Front or side view · hips, knees and feet visible",
  "low-side": "Side view · camera near floor height",
  front: "Front view · keep both sides in frame",
  "three-quarter": "Three-quarter view · both sides visible",
  "low-three-quarter": "Low three-quarter view · keep both limb chains visible",
};
export function recognitionLabel(id: string) {
  const p = exerciseProfile(id);
  return p?.method === "assisted"
    ? "Assisted camera · estimate"
    : p?.method === "confirmation"
      ? "Preview + manual confirmation"
      : "Configured camera · movement tracking";
}
