import {readFile,writeFile,mkdir} from 'node:fs/promises';
const check=process.argv.includes('--check');
await mkdir(new URL('./functions/_shared/',import.meta.url),{recursive:true});
for(const name of ['contracts','game','worldMaps','commands','importSave']){
 const input=await readFile(new URL(`../src/core/${name}.ts`,import.meta.url),'utf8');
 const generated='// GENERATED by node supabase/sync-core.mjs. Edit src/core instead.\n'+input.replace(/from '\.\/(contracts|game|worldMaps|commands)'/g,"from './$1.ts'");
 const path=new URL(`./functions/_shared/${name}.ts`,import.meta.url);
 if(check){if(await readFile(path,'utf8')!==generated)throw new Error(`Server copy differs: ${name}. Run node supabase/sync-core.mjs.`);}
 else await writeFile(path,generated);
}
console.log(check?'Shared game source parity verified.':'Generated shared Edge game modules.');
